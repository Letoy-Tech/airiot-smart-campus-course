-- 教师模板，不是自动执行脚本。先替换所有占位符；每组一库，不使用原平台库。
-- 由课程数据库管理员执行。STUDENT_SOURCE_HOST应是具体允许来源或校内受控网段，不默认开放任意来源。
CREATE DATABASE `COURSE_SCHEMA` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER 'GROUP_RUNTIME_USER'@'STUDENT_SOURCE_HOST' IDENTIFIED BY 'REPLACE_WITH_RANDOM_PASSWORD' REQUIRE SSL;
GRANT SELECT, INSERT, UPDATE, DELETE ON `COURSE_SCHEMA`.* TO 'GROUP_RUNTIME_USER'@'STUDENT_SOURCE_HOST';
-- 迁移账号只由教师使用，与日常运行账号分离。Flyway新建/修改表、索引及读取历史所需权限。
CREATE USER 'GROUP_MIGRATION_USER'@'TEACHER_SOURCE_HOST' IDENTIFIED BY 'REPLACE_WITH_DIFFERENT_RANDOM_PASSWORD' REQUIRE SSL;
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON `COURSE_SCHEMA`.* TO 'GROUP_MIGRATION_USER'@'TEACHER_SOURCE_HOST';
