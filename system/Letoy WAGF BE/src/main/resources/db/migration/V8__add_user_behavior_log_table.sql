CREATE TABLE IF NOT EXISTS user_behavior_log (
    id VARCHAR(64) PRIMARY KEY,
    trace_id VARCHAR(64) NULL,
    uid VARCHAR(64) NULL,
    username VARCHAR(64) NULL,
    request_method VARCHAR(16) NOT NULL,
    request_uri VARCHAR(255) NOT NULL,
    query_string VARCHAR(255) NULL,
    request_target VARCHAR(512) NOT NULL,
    client_ip VARCHAR(64) NULL,
    user_agent VARCHAR(512) NULL,
    platform VARCHAR(64) NULL,
    app_version VARCHAR(64) NULL,
    outcome VARCHAR(32) NOT NULL,
    risk_level VARCHAR(32) NOT NULL,
    http_status INT NOT NULL,
    business_code INT NULL,
    error_message VARCHAR(255) NULL,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_user_behavior_log_uid_time (uid, created_at),
    KEY idx_user_behavior_log_outcome_time (outcome, created_at),
    KEY idx_user_behavior_log_status_time (http_status, created_at),
    KEY idx_user_behavior_log_risk_time (risk_level, created_at)
);
