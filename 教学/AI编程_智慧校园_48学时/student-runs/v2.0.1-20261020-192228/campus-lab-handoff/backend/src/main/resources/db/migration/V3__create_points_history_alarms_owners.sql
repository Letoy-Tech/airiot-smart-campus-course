-- 第10课 V3：建立 points、history_samples、alarms、owners，并用公开教学样本 materials/mock-campus.json 初始化读数。
-- 只新增表与数据，不改已执行过的 V1、V2：这两个文件的校验和必须保持原样，否则启动校验会失败。
-- 数据来源：materials/mock-campus.json（source=TEACHING_MOCK, simulated=true），仅课堂演示，不做真实设备控制。
-- 时间列统一用 BIGINT 保存样本自带的 epoch 毫秒值，不换算成本机当前时间，也不用 NOW() 冒充采样时间。
-- 读数为 NULL 表示“没有读数”，与 0（有效读到 0）是两件事：两种都按样本原样保存。
-- owners 只建表，不写入任何记录；责任人由管理员登记后才有行。

CREATE TABLE points (
    device_id   VARCHAR(16)    NOT NULL COMMENT '设备编号，必须能在 devices 中找到',
    tag_id      VARCHAR(32)    NOT NULL COMMENT '点位标识，如 temperature',
    `value`     DECIMAL(12, 3) NULL COMMENT '最近读数；NULL=没有读数，0=有效读到 0，不得互相替代',
    unit        VARCHAR(16)    NOT NULL COMMENT '单位：°C、%、kW、V；无单位的状态量存空串',
    sample_time BIGINT         NULL COMMENT '样本原始时间（epoch 毫秒）；NULL=没有采样时间，不用当前时间补',
    quality     VARCHAR(16)    NOT NULL COMMENT 'fresh / stale / missing / invalid',
    PRIMARY KEY (device_id, tag_id),
    CONSTRAINT fk_points_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT ck_points_quality CHECK (quality IN ('fresh', 'stale', 'missing', 'invalid'))
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT '点位：d01-d16 共 28 个点位';

CREATE TABLE history_samples (
    device_id   VARCHAR(16)    NOT NULL COMMENT '设备编号',
    tag_id      VARCHAR(32)    NOT NULL COMMENT '点位标识',
    sample_time BIGINT         NOT NULL COMMENT '样本原始时间（epoch 毫秒），只按样本原值保存',
    `value`     DECIMAL(12, 3) NULL COMMENT '样本读数；NULL=该时刻没有读数，0=该时刻有效读到 0',
    PRIMARY KEY (device_id, tag_id, sample_time),
    CONSTRAINT fk_history_samples_point FOREIGN KEY (device_id, tag_id)
        REFERENCES points (device_id, tag_id)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT '历史样本：单位不另存，读取时按点位单位给出，避免两边不一致';

CREATE TABLE alarms (
    id         VARCHAR(16) NOT NULL COMMENT '报警编号，如 a01',
    device_id  VARCHAR(16) NOT NULL COMMENT '来源设备',
    message    VARCHAR(255) NOT NULL COMMENT '原始报警文本，不改写',
    status     VARCHAR(32) NOT NULL COMMENT '原始状态值，如 SAMPLE_ACTIVE',
    `level`    VARCHAR(16) NOT NULL COMMENT '级别，如 NOTICE',
    alarm_time BIGINT      NOT NULL COMMENT '原始报警时间（epoch 毫秒）',
    simulated  TINYINT(1)  NOT NULL DEFAULT 1 COMMENT '1=教学模拟数据',
    PRIMARY KEY (id),
    KEY idx_alarms_device_id (device_id),
    CONSTRAINT fk_alarms_device FOREIGN KEY (device_id) REFERENCES devices (id)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT '原始报警：只查看，不提供确认、恢复、关闭等写操作';

CREATE TABLE owners (
    device_id  VARCHAR(16)  NOT NULL COMMENT '设备编号，一台设备最多一条责任记录',
    username   VARCHAR(32)  NOT NULL COMMENT '负责人账号，必须能在 users 中找到',
    note       VARCHAR(255) NOT NULL DEFAULT '' COMMENT '登记备注',
    version    INT          NOT NULL DEFAULT 0 COMMENT '乐观锁版本：无记录视为 0，首次登记为 1，之后每次 +1',
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (device_id),
    KEY idx_owners_username (username),
    CONSTRAINT fk_owners_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT fk_owners_user FOREIGN KEY (username) REFERENCES users (username)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT '设备责任：初始为空，登记后才有记录';

